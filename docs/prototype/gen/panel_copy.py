def apply_panel_copy(panels: list[dict]) -> list[dict]:
    """把新手文案写回面板；缺文案的面板保持原样，交给构建门禁警告。"""
    for panel in panels:
        copy = PANEL_COPY.get(panel["id"])
        if not copy:
            continue
        panel.update(copy)
    return panels
